"""Core data models for the Cross-Border FX & Treasury Risk Engine."""

from __future__ import annotations

from datetime import datetime
from decimal import Decimal
from enum import Enum
from typing import Any, Optional

from pydantic import BaseModel, Field, field_validator


class DataSource(str, Enum):
    """Enumeration of supported data sources."""

    FRED = "FRED"
    FRANKFURTER = "FRANKFURTER"
    ARGENTINA_DATOS = "ARGENTINA_DATOS"
    BCRA = "BCRA"
    COINGECKO = "COINGECKO"
    INDEC = "INDEC"


class Currency(str, Enum):
    """Supported currencies for the treasury engine."""

    USD = "USD"
    EUR = "EUR"
    BRL = "BRL"
    MXN = "MXN"
    ARS = "ARS"
    USDT = "USDT"
    USDC = "USDC"


class RateType(str, Enum):
    """Type of exchange rate."""

    OFFICIAL = "OFFICIAL"
    FINANCIAL = "FINANCIAL"
    BLUE = "BLUE"
    MID_MARKET = "MID_MARKET"
    SPOT = "SPOT"


class Rate(BaseModel):
    """A single exchange rate data point with financial precision."""

    source: DataSource
    base_currency: Currency
    target_currency: Currency
    rate: Decimal = Field(..., description="Exchange rate with Decimal precision")
    rate_type: RateType = RateType.MID_MARKET
    timestamp: datetime
    metadata: dict[str, Any] = Field(default_factory=dict)

    @field_validator("rate", mode="before")
    @classmethod
    def validate_rate(cls, v: Any) -> Decimal:
        if isinstance(v, str):
            return Decimal(v)
        if isinstance(v, float):
            return Decimal(str(v))
        return Decimal(v)


class RateCollection(BaseModel):
    """A collection of rates from a single source fetch."""

    source: DataSource
    rates: list[Rate]
    fetched_at: datetime
    success: bool = True
    error: Optional[str] = None


class Spread(BaseModel):
    """A spread between two rates (arbitrage opportunity)."""

    source_a: DataSource
    source_b: DataSource
    base_currency: Currency
    target_currency: Currency
    rate_a: Decimal
    rate_b: Decimal
    spread_bps: Decimal = Field(..., description="Spread in basis points")
    direction: str = Field(..., description="BUY or SELL signal")
    timestamp: datetime


class Exposure(BaseModel):
    """Multi-currency treasury exposure position."""

    currency: Currency
    amount: Decimal
    base_currency: Currency = Currency.USD
    exchange_rate: Decimal
    adjusted_amount: Decimal = Field(
        ..., description="Amount adjusted for inflation"
    )
    timestamp: datetime


class ArbitrageSignal(BaseModel):
    """An arbitrage signal generated by the engine."""

    base_currency: Currency
    target_currency: Currency
    recommended_action: str = Field(..., description="BUY, SELL, or HOLD")
    confidence: Decimal = Field(..., ge=0, le=1)
    spread_bps: Decimal
    expected_savings_usd: Decimal
    sources: list[DataSource]
    timestamp: datetime
